/**
 * Places a point `km` from `origin` on a compass bearing. Jobs are positioned relative to the
 * Simulator's default location (Apple Park) so the distances in the README are exact.
 */
function place(origin, km, bearingDeg) {
  const b = (bearingDeg * Math.PI) / 180;
  const latitude = origin.latitude + (km * Math.cos(b)) / 111.32;
  const longitude = origin.longitude + (km * Math.sin(b)) / (111.32 * Math.cos((origin.latitude * Math.PI) / 180));
  return { latitude: +latitude.toFixed(5), longitude: +longitude.toFixed(5) };
}

